import assert from 'node:assert/strict';
import fs from 'node:fs';
import {deriveStats,simulationParams,simulate,PASS,IDS} from '../dist/simulator.js';
const catalog=JSON.parse(fs.readFileSync(new URL('../dist/catalog.json',import.meta.url)));
const crossbow=catalog.equipment.find(i=>i.category==='Crossbow');
const state={items:{weapon1:{id:crossbow.id,level:0,traits:[]}},attrs:{str:10,dex:10,Int:10,per:10,con:10},attrMode:'base',active:[IDS.rapid],passive:[],defensive:[],specs:{},masteryTrees:{},mastery:{}};
const params=simulationParams(state,catalog,{hp:1,crossMin:9999,speed:200,bonus:900,mana:1,sheetIncludesPassives:0,resistance:150,latency:.1});
const derived=deriveStats(state,catalog);
for(const key of ['hp','crossMin','speed','bonus','mana'])assert.equal(params[key],derived[key],`${key} must come from the build`);
assert.equal(params.resistance,150);assert.equal(params.latency,.1);assert.equal(params.sheetIncludesPassives,1);
const next=structuredClone(state);next.attrs.str=30;
assert(simulationParams(next,catalog).hp>params.hp,'attribute change must change simulator HP');
next.passive=[PASS.bonus];
const withPassive=simulationParams(next,catalog);
assert.equal(withPassive.bonus,deriveStats({...next,passive:[]},catalog).bonus+13);
const combat={catalog,state:next,params:withPassive,priority:[IDS.rapid],duration:5};
const once=simulate(combat),twice=simulate({...combat,params:{...withPassive,sheetIncludesPassives:0}});
assert(twice.total>once.total,'build passives must not be added a second time by the simulator');
console.log('Build-only simulation: overrides rejected, attributes updated, combat settings retained, passives counted once.');
