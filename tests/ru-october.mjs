import assert from 'node:assert/strict';
import fs from 'node:fs';
import {SLOTS,itemStats,totalAttributes} from '../engine.js';
import {maxRuneChoices,maxRuneSelection,runeEffects} from '../runes.js';
import {combatRatings} from '../position-combat.js';
import {DEFAULTS,IDS,deriveStats,expectedHit,simulate,simulationParams} from '../simulator.js';
const catalog=JSON.parse(fs.readFileSync(new URL('../catalog.json',import.meta.url)));
const state={items:{},attrs:{str:10,dex:10,Int:10,per:10,con:10},active:[],passive:[],defensive:[],specs:{}};
const near=(a,b)=>assert(Math.abs(a-b)<1e-8,`${a} != ${b}`);
assert.equal(SLOTS.length,14);assert.equal(SLOTS.filter(s=>s[2]==='Earring').length,1);
const earrings=catalog.equipment.filter(i=>i.slot==='Earring');assert.equal(earrings.length,6);
const ear=earrings.find(i=>i.id==='ear_aa_t2_normal_001');
const traits=ear.traits.filter(t=>t.startsWith('kSide')).map(id=>({id,level:4}));
const entry={id:ear.id,level:12,traits};
const stats=itemStats(ear,12,traits,catalog);
assert.equal(stats.dex,7);assert.equal(stats.cost_consumption_modifier,900);assert.equal(stats.magic_armor,360);
assert.equal(stats.front_evasion,1640);assert.equal(stats.side_critical_attack,1200);
assert.equal(totalAttributes({...state,items:{earring:entry}},catalog).dex,17);
const base=deriveStats(state,catalog),gear=deriveStats({...state,items:{earring:entry}},catalog);
near(gear.sideCrit,120);near(gear.sideHeavy,120);near(gear.efficiency-base.efficiency,9);
assert.equal(gear.critR-base.critR,35,'DEX from earrings changes general ratings; directional traits stay separate');
const choices=maxRuneChoices(ear);assert.equal(choices.length,3);assert(choices.every(r=>r.thumbnail.includes('Earring')));
const bossStat=choices.find(r=>r.type==='Attack').statPool.find(r=>r.stat==='boss_range_critical_attack').stat;
const runes=[maxRuneSelection(ear,'Attack',bossStat),maxRuneSelection(ear,'Defense'),maxRuneSelection(ear,'Assist')];
const effects=runeEffects(ear,{...entry,runes},catalog);assert(effects.synergy.length);assert(effects.stats[bossStat]>0);
const bossBuild=simulationParams({...state,items:{earring:{...entry,runes}}},catalog);
assert(combatRatings(bossBuild,'Crossbow','front').critical>combatRatings({...bossBuild,targetIsBoss:0},'Crossbow','front').critical);
const p={...DEFAULTS,crossMin:100,crossMax:200,wandMin:100,wandMax:200,critR:1000,mana:1e6,auto:0,sideCrit:120,sideHeavy:120};
near(combatRatings(p,'Crossbow','front').critical,.5);
near(combatRatings(p,'Crossbow','side').critical,1120/2120);
near(combatRatings(p,'Crossbow','back').critical,.53);
assert.equal(combatRatings(p,'Crossbow','best').position,'side','best direction can be the flank, not always the back');
near(expectedHit(p,'Crossbow',1,0),175);
const once=(pos,ghost=false)=>simulate({catalog,state:{...state,specs:ghost?{[IDS.ghost]:['SkillSet_WP_CR_S_GhostWalk_Trait_4']}:{}},params:{...p,attackPosition:pos},priority:ghost?[IDS.ghost,IDS.decay]:[IDS.decay],overrides:{[IDS.ghost]:{cooldownSec:999,cast:0,hitDelay:0},[IDS.decay]:{cooldownSec:999,cast:0,hitDelay:0}}},true);
assert(!once('front').damage[IDS.decay]);assert(once('side').damage[IDS.decay]>0);assert(once('front',true).damage[IDS.decay]>0);
const expired=simulate({catalog,state:{...state,specs:{[IDS.ghost]:['SkillSet_WP_CR_S_GhostWalk_Trait_4']}},params:{...p,attackPosition:'front'},priority:[IDS.ghost,IDS.decay],overrides:{[IDS.ghost]:{cooldownSec:999,cast:8,hitDelay:0},[IDS.decay]:{cooldownSec:999,cast:0,hitDelay:0}}},true);
assert(!expired.damage[IDS.decay],'best-direction attacks end with the Ghost buff');
const dex80=catalog.attributes.milestones.find(x=>x.attribute==='DEX'&&x.count===80);
assert.equal(dex80.bonuses.find(x=>x.stat==='damage_reduction_penetration').value,9);
console.log('RU October: six earrings, +12 stats, directional traits, boss runes, best-direction buff, Decay damage, and 80 DEX bonus passed.');
